function skillRenderSnapshotTable(agents, zh) {
  const header = zh
    ? "| ID | 名称 | 感知 | 托管 | MCP | 凭据模型 | 反爬 | 定价 | 许可 | 核对 |"
    : "| ID | Name | Perception | Host | MCP | Credentials | Anti-bot | Price | License | Checked |";
  const sep = "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |";
  const rows = agents.map(
    (a) =>
      `| \`${a.id}\` | ${a.name} | ${a.perception} | ${a.hosting} | ${a.mcp} | \`${a.authModel}\` | ${a.antiBotBadge} | ${a.pricingBadge} | ${a.license} | ${a.lastChecked} |`
  );
  return [header, sep, ...rows].join("\n");
}

